                <li>Customize primary, secondary, and accent colors</li>
                <li>Colors appear on the digital ticket</li>
                <li>Use color picker or enter hex codes</li>
                <li>Preview changes in real-time</li>
            </ul>
        </div>

        <div class="border border-gray-200 dark:border-gray-700 rounded-lg p-4">
            <h4 class="font-semibold text-gray-900 dark:text-gray-100 mb-2">Buying Additional Tickets</h4>
            <ul class="text-gray-600 dark:text-gray-400 text-sm space-y-1 list-disc list-inside">
                <li>If you reach your subscription's ticket limit, you can buy more</li>
                <li>Click "Buy Additional Tickets" in the Tickets section</li>
                <li>Select a pricing plan</li>
                <li>Apply discount codes if available</li>
                <li>Complete payment via Xendit</li>
