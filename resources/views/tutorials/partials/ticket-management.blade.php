            <h4 class="font-semibold text-gray-900 dark:text-gray-100 mb-2">Creating Ticket Types</h4>
            <ul class="text-gray-600 dark:text-gray-400 text-sm space-y-1 list-disc list-inside">
                <li>Navigate to your event's "Tickets" section</li>
                <li>Click "Add Ticket Type" button</li>
                <li>Enter ticket name (e.g., "Early Bird", "VIP", "Student")</li>
                <li>Set price (use 0 for free tickets)</li>
                <li>Define quantity (based on your subscription limit)</li>
                <li>Add a description (max 70 characters - shown on purchase page)</li>
                <li>Set sale start/end dates (optional)</li>
                <li>Mark as active/inactive</li>
            </ul>
        </div>

