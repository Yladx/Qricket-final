            <ul class="text-gray-600 dark:text-gray-400 text-sm space-y-1 list-disc list-inside">
                <li><strong>Max tickets per order:</strong> Limit how many tickets can be purchased in one transaction</li>
                <li><strong>Refund policy:</strong> Set your refund terms and conditions</li>
                <li><strong>Allow refunds:</strong> Enable/disable refund requests</li>
                <li><strong>Require approval:</strong> Manually approve refund requests</li>
                <li><strong>Allow ticket sharing:</strong> Let buyers share tickets with others</li>
                <li><strong>Limit per user:</strong> Restrict how many tickets one user can buy</li>
            </ul>
        </div>

